"""The web editor's help for each setting, from the manual's Settings menu table.

Reads the "Every item, with its default" table in docs/tboss/manual.md and writes
webapp/tb-help.js: for each page and item (keyed by the names the board shows, e.g.
"PLAY/CHORD VEL"), the manual's name, its values and default as small HTML, with the
manual's links pointing at the site's manual page. The editor's Settings tab (1.9.0) shows them
beside the controls it builds from the board's own menu.
Run after editing that table:   python scripts/gen_settings_help.py
Check that tb-help.js matches:  python scripts/gen_settings_help.py --check
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# The manual: docs/tboss/manual.md here, docs/manual.md in the published TBOSS repository.
MANUAL = next((p for p in (ROOT / 'docs/tboss/manual.md', ROOT / 'docs/manual.md') if p.exists()), ROOT / 'docs/tboss/manual.md')
OUT = ROOT / 'webapp/tb-help.js'
START = 'Every item, with its default'
NOTE = re.compile(r'\s*\*\((opt|\d+\.\d+)\)\*')


def inline(text):
    """The manual's inline markdown (links, `code`, *italics*) as HTML; links open the manual."""
    out = html.escape(text, quote=False)
    out = re.sub(r'`([^`]+)`', r'<code>\1</code>', out)
    out = re.sub(r'\[([^\]]+)\]\(#([\w-]+)\)', r'<a href="manual#\2" target="_blank">\1</a>', out)
    out = re.sub(r'\*([^*]+)\*', r'<i>\1</i>', out)
    return out


def rows():
    lines = MANUAL.read_text(encoding='utf-8').splitlines()
    at = next(i for i, line in enumerate(lines) if line.startswith(START))
    table = []
    for line in lines[at + 1:]:
        if line.startswith('|'):
            table.append(line)
        elif table:
            break
    out, page = [], None
    for line in table[2:]:  # past the header and its rule
        cells = [c.strip() for c in line.strip().strip('|').split('|')]
        if len(cells) != 4:
            raise SystemExit(f'manual table row without 4 cells: {line}')
        page = cells[0] or page
        out.append((page, cells[1], cells[2], cells[3]))
    return out


def pages():
    """The manual's page names by the board's (PLAY: Play)."""
    return {page.upper(): page for page, *_ in rows() if not page.startswith('Every page')}


def entries():
    help_ = {}
    for page, item, values, default in rows():
        notes = NOTE.findall(item)
        name = NOTE.sub('', item).strip()
        page_key = '*' if page.startswith('Every page') else page.upper()
        names = ['*'] if page_key == 'BUTTONS' and '…' in name else re.split(r', | / ', name)
        for one in names:
            key = f'{page_key}/{one.upper()}'
            if key in help_:
                raise SystemExit(f'two manual rows for {key}')
            help_[key] = {'name': one, 'values': inline(values), 'default': inline(default),
                          'optional': 'opt' in notes, 'since': next((n for n in notes if n != 'opt'), '')}
    return help_


def render():
    body = json.dumps(entries(), ensure_ascii=False, indent=0, sort_keys=True)
    return ('// SPDX-License-Identifier: GPL-3.0-or-later - generated by scripts/gen_settings_help.py from the\n'
            "// Settings menu table in docs/tboss/manual.md; don't edit. Keys: the board's page and item names\n"
            '// (PAGE/ITEM; */RESET OPTIONS on every page, BUTTONS/* every center button).\n'
            f'export const PAGES = {json.dumps(pages(), ensure_ascii=False)};\n'
            f'export const HELP = {body};\n')


def main():
    text = render()
    if '--check' in sys.argv:
        if OUT.read_text(encoding='utf-8') != text:
            raise SystemExit(f'{OUT.relative_to(ROOT)} is out of date: run python scripts/gen_settings_help.py')
        print('tb-help.js matches the manual')
        return
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)} ({len(entries())} items)')


if __name__ == '__main__':
    main()
