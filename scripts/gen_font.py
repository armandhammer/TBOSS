def main():
    for ch, rows in ART.items():
        assert len(rows) == 7 and all(len(r) == 5 and set(r) <= set('.#') for r in rows), ch
    chars = ''.join(sorted(ART))
    lines = ['/* SPDX-License-Identifier: GPL-3.0-or-later - original 5x7 font, generated by scripts/gen_font.py. */',
             '#include "display.h"',
             f'const char td_font_chars[] = "{chars}";',
             'const uint8_t td_font_rows[][7] = {']
    for ch in chars:
        rows = ', '.join(f'0x{int(r.replace("#", "1").replace(".", "0"), 2):02x}' for r in ART[ch])
        lines.append(f"    {{{rows}}}, /* '{ch}' */")
    lines += ['};', '']
    out = Path(__file__).resolve().parents[1] / 'src/tb/font.c'
    out.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{len(chars)} glyphs -> {out}')


if __name__ == '__main__':
    main()
